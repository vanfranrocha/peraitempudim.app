-- =========================================================
-- updated_at automático
-- =========================================================

create or replace function public.set_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger products_set_updated_at
before update on public.products
for each row execute function public.set_updated_at();

create trigger product_availability_set_updated_at
before update on public.product_availability
for each row execute function public.set_updated_at();

create trigger store_settings_set_updated_at
before update on public.store_settings
for each row execute function public.set_updated_at();

create trigger store_hours_set_updated_at
before update on public.store_hours
for each row execute function public.set_updated_at();

create trigger delivery_ranges_set_updated_at
before update on public.delivery_ranges
for each row execute function public.set_updated_at();

create trigger orders_set_updated_at
before update on public.orders
for each row execute function public.set_updated_at();

